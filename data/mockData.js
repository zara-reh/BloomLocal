// Every half-zone from low to high, for example zones('7a', '9b').
function zones(low, high) {
  const all = [];
  for (let number = 1; number <= 13; number++) {
    all.push(`${number}a`, `${number}b`);
  }
  return all.slice(all.indexOf(low), all.indexOf(high) + 1);
}

